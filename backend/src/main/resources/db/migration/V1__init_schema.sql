-- EduvIA: esquema inicial. Flyway es la única fuente del esquema.
create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- Identidad y autenticación
-- ---------------------------------------------------------------------------
create table users (
    id            bigint generated by default as identity primary key,
    full_name     varchar(200)  not null,
    email         varchar(320)  not null,
    phone         varchar(20)   not null,
    role          varchar(16)   not null,
    password_hash varchar(100)  not null,
    created_at    timestamptz   not null default now(),
    updated_at    timestamptz   not null default now(),
    constraint ck_users_role check (role in ('PARENT', 'TEACHER')),
    constraint ck_users_email_format check (email like '%@%'),
    constraint ck_users_phone_digits check (phone ~ '^[0-9]+$'),
    constraint uk_users_email unique (email),
    constraint uk_users_phone unique (phone)
);

create table refresh_tokens (
    id          bigint generated by default as identity primary key,
    user_id     bigint      not null,
    token_hash  varchar(64) not null,
    expires_at  timestamptz not null,
    revoked_at  timestamptz,
    created_at  timestamptz not null default now(),
    constraint fk_refresh_tokens_user foreign key (user_id) references users (id) on delete cascade,
    constraint uk_refresh_tokens_hash unique (token_hash)
);
create index idx_refresh_tokens_user on refresh_tokens (user_id);

create table password_reset_codes (
    id            bigint generated by default as identity primary key,
    user_id       bigint      not null,
    code          varchar(6)  not null,
    expires_at    timestamptz not null,
    attempts_left integer     not null default 5,
    used_at       timestamptz,
    created_at    timestamptz not null default now(),
    constraint fk_password_reset_codes_user foreign key (user_id) references users (id) on delete cascade,
    constraint ck_password_reset_codes_code check (code ~ '^[0-9]{6}$'),
    constraint ck_password_reset_codes_attempts check (attempts_left >= 0)
);
create index idx_password_reset_codes_user on password_reset_codes (user_id);

-- ---------------------------------------------------------------------------
-- Grupos y alumnos
-- ---------------------------------------------------------------------------
create table school_groups (
    id            bigint generated by default as identity primary key,
    name          varchar(100) not null,
    school        varchar(200) not null,
    subject       varchar(200) not null default '',
    code          varchar(16)  not null,
    teacher_id    bigint       not null,
    student_count integer      not null default 0,
    created_at    timestamptz  not null default now(),
    updated_at    timestamptz  not null default now(),
    constraint fk_school_groups_teacher foreign key (teacher_id) references users (id) on delete restrict,
    constraint ck_school_groups_code check (code ~ '^[A-Z0-9]{2}-[A-Z0-9]{4}$'),
    constraint ck_school_groups_student_count check (student_count >= 0),
    constraint uk_school_groups_code unique (code)
);
create index idx_school_groups_teacher on school_groups (teacher_id);
create index idx_school_groups_code_lower on school_groups (lower(code));

create table students (
    id         bigint generated by default as identity primary key,
    name       varchar(200) not null,
    group_id   bigint       not null,
    parent_id  bigint,
    created_at timestamptz  not null default now(),
    updated_at timestamptz  not null default now(),
    constraint fk_students_group foreign key (group_id) references school_groups (id) on delete cascade,
    constraint fk_students_parent foreign key (parent_id) references users (id) on delete restrict,
    constraint ck_students_name check (length(trim(name)) > 0)
);
create index idx_students_group on students (group_id);
create index idx_students_parent on students (parent_id);

-- ---------------------------------------------------------------------------
-- Tareas
-- ---------------------------------------------------------------------------
create table school_tasks (
    id             bigint generated by default as identity primary key,
    group_id       bigint       not null,
    title          varchar(200) not null,
    subject        varchar(16)  not null,
    description    text         not null default '',
    due_date       date         not null,
    published_date date         not null,
    teacher_name   varchar(100) not null,
    total_students integer      not null default 0,
    has_photo      boolean      not null default false,
    created_at     timestamptz  not null default now(),
    updated_at     timestamptz  not null default now(),
    constraint fk_school_tasks_group foreign key (group_id) references school_groups (id) on delete cascade,
    constraint ck_school_tasks_subject check (subject in ('MATEMATICAS', 'ESPANOL', 'CIENCIAS', 'HISTORIA', 'OTRA')),
    constraint ck_school_tasks_title check (length(trim(title)) > 0),
    constraint ck_school_tasks_total check (total_students >= 0)
);
create index idx_school_tasks_group_due on school_tasks (group_id, due_date);

create table task_deliveries (
    task_id      bigint      not null,
    student_id   bigint      not null,
    delivered_at timestamptz not null default now(),
    constraint pk_task_deliveries primary key (task_id, student_id),
    constraint fk_task_deliveries_task foreign key (task_id) references school_tasks (id) on delete cascade,
    constraint fk_task_deliveries_student foreign key (student_id) references students (id) on delete cascade
);
create index idx_task_deliveries_student on task_deliveries (student_id);

-- ---------------------------------------------------------------------------
-- Juntas
-- ---------------------------------------------------------------------------
create table meetings (
    id                bigint generated by default as identity primary key,
    group_id          bigint       not null,
    title             varchar(200) not null,
    date              date         not null,
    time              varchar(20)  not null,
    location          varchar(200) not null,
    has_virtual_link  boolean      not null default false,
    virtual_link      varchar(500),
    reminder_enabled  boolean      not null default true,
    created_at        timestamptz  not null default now(),
    updated_at        timestamptz  not null default now(),
    constraint fk_meetings_group foreign key (group_id) references school_groups (id) on delete cascade,
    constraint ck_meetings_title check (length(trim(title)) > 0),
    constraint ck_meetings_time check (length(trim(time)) > 0),
    constraint ck_meetings_location check (length(trim(location)) > 0)
);
create index idx_meetings_group_date on meetings (group_id, date);
-- Unicidad funcional (case-insensitive): PostgreSQL no admite expresiones en UNIQUE de tabla.
create unique index uk_meetings_unique on meetings (group_id, date, lower(time), lower(location));

create table meeting_responses (
    meeting_id bigint      not null,
    student_id bigint      not null,
    response   varchar(16) not null,
    updated_at timestamptz not null default now(),
    constraint pk_meeting_responses primary key (meeting_id, student_id),
    constraint fk_meeting_responses_meeting foreign key (meeting_id) references meetings (id) on delete cascade,
    constraint fk_meeting_responses_student foreign key (student_id) references students (id) on delete cascade,
    constraint ck_meeting_response check (response in ('PENDING', 'ATTENDING', 'DECLINED'))
);
create index idx_meeting_responses_student on meeting_responses (student_id);

-- ---------------------------------------------------------------------------
-- Calendario: el id lo comparte con la tarea/junta que origina el evento.
-- ---------------------------------------------------------------------------
create sequence calendar_events_id_seq as bigint;

create table calendar_events (
    id         bigint       primary key default nextval('calendar_events_id_seq'),
    group_id   bigint       not null,
    date       date         not null,
    type       varchar(16)  not null,
    title      varchar(200) not null,
    subtitle   varchar(200) not null default '',
    created_at timestamptz  not null default now(),
    updated_at timestamptz  not null default now(),
    constraint fk_calendar_events_group foreign key (group_id) references school_groups (id) on delete cascade,
    constraint ck_calendar_event_type check (type in ('TASK', 'MEETING', 'EXAM'))
);
create index idx_calendar_events_group_date on calendar_events (group_id, date);
